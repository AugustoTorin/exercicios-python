# Ex 02: Leia três números reais e calcule a média aritmética. Exiba o resultado.

n1 = int(input('Digite o primeiro número: '))
n2 = int(input('Digite o segundo número: '))
n3 = int(input('Digite o terceiro número: '))

media_aritmética = (n1 + n2 + n3) / 3

print(f'A média aritmética dos três números é {media_aritmética}')